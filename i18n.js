function t(source, vars) {
  const lang = (window.ILIM_LANGUAGE || 'tr') === 'en' ? 'en' : 'tr';
  let out = source == null ? '' : String(source);
  if (lang === 'en' && window.ILIM_I18N && window.ILIM_I18N.en && Object.prototype.hasOwnProperty.call(window.ILIM_I18N.en, out)) {
    out = window.ILIM_I18N.en[out];
  }
  if (vars) {
    out = out.replace(/\{(\w+)\}/g, (match, key) =>
      Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match);
  }
  return out;
}

const I18N_SKIP_SELECTOR = [
  'script', 'style', 'textarea', 'code', 'pre',
  '[data-no-i18n]', '[data-no-i18n] *',
  '.post-text', '.review-text', '.quote-text', '.comment-text', '.note-text',
  '.comment-bubble', '.support-reply p', '.writing-item p', '.note-card p',
  '.public-quote p', '.chat-message__text', '.group-message__text',
  '.announcement-card p', '.quote-source', '.book-cover__title', '.book-cover__author',
  '.profile-bio', '.user-bio'
].join(', ');

// textarea içeriği kullanıcı verisi olduğu için metin düğümlerinden atlanır;
// ancak placeholder/title/aria-label gibi arayüz nitelikleri çevrilmelidir.
const I18N_ATTR_SKIP_SELECTOR = I18N_SKIP_SELECTOR
  .split(', ')
  .filter((selector) => selector !== 'textarea')
  .join(', ');

function translatedValue(value) {
  const lang = (window.ILIM_LANGUAGE || 'tr') === 'en' ? 'en' : 'tr';
  if (lang !== 'en') return value;
  const dict = window.ILIM_I18N.en;
  return Object.prototype.hasOwnProperty.call(dict, value) ? dict[value] : value;
}

const I18N_TEXT_ORIGINALS = new WeakMap();
const I18N_ATTR_ORIGINALS = new WeakMap();

function translateTextNodes(root = document) {
  const lang = (window.ILIM_LANGUAGE || 'tr') === 'en' ? 'en' : 'tr';
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walk.nextNode()) nodes.push(walk.currentNode);

  nodes.forEach((node) => {
    const parent = node.parentElement;
    if (!parent || parent.closest(I18N_SKIP_SELECTOR)) return;
    let raw = I18N_TEXT_ORIGINALS.get(node);
    if (raw === undefined) {
      raw = node.nodeValue;
      I18N_TEXT_ORIGINALS.set(node, raw);
    }
    if (!raw || !raw.trim()) return;
    const trimmed = raw.trim();
    if (trimmed === '×' || trimmed === '★' || trimmed === '✦') return;
    const translated = lang === 'en' ? translatedValue(trimmed) : trimmed;
    const lead = raw.slice(0, raw.indexOf(trimmed));
    const tail = raw.slice(raw.indexOf(trimmed) + trimmed.length);
    const next = lead + translated + tail;
    if (node.nodeValue !== next) node.nodeValue = next;
  });

  const attrs = ['placeholder', 'title', 'aria-label'];
  root.querySelectorAll('*').forEach((el) => {
    if (el.closest(I18N_ATTR_SKIP_SELECTOR)) return;
    let originals = I18N_ATTR_ORIGINALS.get(el);
    if (!originals) {
      originals = {};
      I18N_ATTR_ORIGINALS.set(el, originals);
    }
    attrs.forEach((attr) => {
      if (!el.hasAttribute(attr)) return;
      if (!(attr in originals)) originals[attr] = el.getAttribute(attr);
      const next = lang === 'en' ? translatedValue(originals[attr]) : originals[attr];
      if (el.getAttribute(attr) !== next) el.setAttribute(attr, next);
    });
  });
}

function applyStaticI18n(root = document) {
  const nodes = root.querySelectorAll('[data-i18n], [data-i18n-placeholder], [data-i18n-aria], [data-i18n-title]');
  nodes.forEach((el) => {
    if (el.hasAttribute('data-i18n')) el.textContent = t(el.getAttribute('data-i18n'));
    if (el.hasAttribute('data-i18n-placeholder')) el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    if (el.hasAttribute('data-i18n-aria')) el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    if (el.hasAttribute('data-i18n-title')) el.title = t(el.getAttribute('data-i18n-title'));
  });
  translateTextNodes(root);
}
